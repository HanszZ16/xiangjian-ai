import type { ChartBase } from '../divination/types'

type AnyChart = ChartBase & Record<string, unknown>

const fallback = (sections: string[]) => sections.map((title, i) => (
  `## ${title}\n\n这是第 ${i + 1} 节的本地预览内容。正式起盘后，这里会由你配置的模型根据上方盘面逐项解读；预览模式不会发出任何网络请求。`
)).join('\n\n')

/** 开发环境里的纯本地示例文案，只用于检查长结果的布局与导出。 */
export function demoReadingFor(moduleId: string, chart: ChartBase, sections: string[]) {
  const c = chart as AnyChart

  if (moduleId === 'bazi') {
    const dayMaster = String(c.dayMaster ?? '日主')
    const current = Array.isArray(c.decades) && typeof c.currentDecade === 'number'
      ? (c.decades as Array<{ ganzhi: string }>)[c.currentDecade]?.ganzhi
      : undefined
    return `## 日主旺衰

此盘以**${dayMaster}日主**为轴，先察月令，再看通根与透干。这里展示的是排版示例：正式解读会逐一指出判断来自哪一柱、哪一支，不用一句放在谁身上都成立的空话。

> 《滴天髓》重在察气势流通；古法只作解释框架，盘面数据仍以上方本地计算为准。

## 十神与六亲

- 先看月柱对日主的牵引，再看年、时两端如何呼应。
- 六亲只谈关系倾向，不替现实经历下结论。
- 时辰存疑时，与时柱有关的内容应当从略。

## 五行喜忌与调候

五行图适合先看偏聚与流通，不能把数值最少的一项简单等同于“人生缺什么”。正式解读会同时考虑季节寒暖燥湿与生克路径。

## 格局成败

格局要由月令、透干、根气共同成立。证据不足时应直说格局未清，而不是为了完整感硬安一个名称。

## 大运

当前大运为**${current ?? '盘中标出的行运'}**。时间轴把十年阶段放在同一视线内，当前一步用朱砂标出，方便与原局来回对照。

## 流年

流年只在原局与大运的背景下讨论。正式解读会围绕用户所问，把前后年份作为时间窗口，而不是承诺某件事必然发生。

## 印证

- [印证] 2018年（示例）｜ 学业、工作或居所节奏出现一次明显转换
- [印证] 2022年（示例）｜ 一段长期安排经历重新取舍

这两条只为测试交互样式，不代表真实推断。

## 趋吉之道

### 今天可做

把当前最想确认的问题写具体：涉及谁、发生在什么时间、你正在两条什么路径之间选择。正式解读会据此减少泛泛而谈。`
  }

  if (moduleId === 'yinyuan') {
    return `## 缘分总览

本地合参指数为**${String(c.score ?? '—')}**。这个数字是年柱、日柱与五行关系的阅读索引，不是感情成功率，也不能替双方作决定。

## 年柱与日柱

盘面把两人的四柱并列展示。正式解读会点名具体干支的合、冲、刑、害，不把生肖一句话扩写成宿命结论。

## 五行互补

- 对照两边同一五行的强弱与补位。
- 同旺可能形成默契，也可能把同一种反应放大。
- 所谓互补最终仍要落到真实的分工与边界。

## 相处动力

这里会把术语翻译成决策速度、表达习惯和共同生活节奏，方便核对，而不是编造两个人的过去。

## 风险与边界

盘中的张力不能合理化控制、欺骗或伤害。现实关系的安全与尊重永远优先。

## 经营建议

双方各自说清一个不可退让的边界，再共同约定一个能观察到的行动，比追问“天生配不配”更有用。`
  }

  if (moduleId === 'fengshui') {
    return `## 宅与人

此宅为**${String(c.houseGua ?? '—')}宅**，常住者命卦为**${String(c.residentGua ?? '—')}**。宅命关系只作为空间取舍的第二层参照，采光、通风、结构与消防始终在前。

## 八方落位

九宫图已把生气、延年、天医、伏位和四个需要降频的位置排开。颜色用于识别用途，不把任何方位描述成不可居住。

## 重点空间

- 工作位优先检查光线、噪声与背后是否稳定，再参考生气或伏位。
- 睡眠位优先避开潮湿、强光、持续噪声与危险动线。
- 没有户型信息的房间，应标为“尚需核对”。

## 形势核对

现场依次检查自然采光、对流通风、墙体潮湿、门窗动线与火源距离。能通过普通空间调整解决的问题，不归咎于神秘煞气。

## 可执行调整

### 今天可做

先移动常坐位、整理遮挡、调整照明；涉及拆改和电气的事项交给专业人员评估。

## 边界说明

当前为八方级初筛。没有实测罗盘度数和户型落宫，不排二十四山玄空飞星。`
  }

  if (moduleId === 'tarot') {
    return `## 整体能量

这副牌的本地抽牌种子已经固定。预览模式保留真实牌面，但以下文字只是为了检查结果页，不构成正式读牌。

## 逐牌

- 每张牌先说明它在牌阵里的位置，再选择一个清晰透镜。
- 逆位按阻塞、过度、内化、延迟或反转择一解释，不简单读成相反。

## 牌间关系

相邻牌可以构成因果、对话、递进或转折，正式解读必须说明依据。

## 综合

把牌面串成“起点、张力、转折、出口、回响”，并落到一周内可以执行的动作。

## 一个问题

此刻哪一项具体行动，最能帮你验证自己的判断？`
  }

  return fallback(sections)
}
